defmodule ThereishWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :thereish

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  # `max_age` is a decade rather than the one-day default because the session
  # carries the device token that finds a player's Seat, and Seats never expire.
  # A cookie that lapses would hand Mara a name form instead of her own Seat.
  # The key keeps the former OTP app's name so a deploy does not drop those Seats.
  @session_options [
    store: :cookie,
    key: "_meaning_game_key",
    signing_salt: "7oltjxex",
    same_site: "Lax",
    max_age: 60 * 60 * 24 * 365 * 10
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, session: @session_options]],
    longpoll: [connect_info: [:peer_data, session: @session_options]]

  # MediaStatic halts the /media prefix before Plug.Static, including when it
  # sends no file. "media" stays in static_paths: in dev, raise_on_missing_only
  # is true, and a file that still lives under priv/static would raise if it
  # were removed.
  plug ThereishWeb.Plugs.MediaStatic

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :thereish,
    gzip: not code_reloading?,
    only: ThereishWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :thereish
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug ThereishWeb.Router
end
